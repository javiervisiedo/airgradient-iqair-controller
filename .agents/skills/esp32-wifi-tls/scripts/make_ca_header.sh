#!/usr/bin/env bash
# Emit a C header with trusted root CAs for api.airgradient.com to stdout.
# Diagnostics (served chain) go to stderr.
#   make_ca_header.sh > include/ca_certs.h
set -euo pipefail
HOST="${1:-api.airgradient.com}"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

echo ">> Chain currently served by $HOST:" >&2
echo | openssl s_client -connect "$HOST:443" -servername "$HOST" -showcerts 2>/dev/null \
  | grep -E '^ *[0-9]+ s:|^ *i:' >&2 || echo "   (could not connect)" >&2

curl -fsSL https://letsencrypt.org/certs/isrgrootx1.pem  -o "$TMP/x1.pem"
curl -fsSL https://letsencrypt.org/certs/isrg-root-x2.pem -o "$TMP/x2.pem"

for f in x1 x2; do
  openssl x509 -in "$TMP/$f.pem" -noout -subject -enddate >&2
done

echo "// Generated by .agents/skills/esp32-wifi-tls/scripts/make_ca_header.sh on $(date -u +%Y-%m-%d)"
echo "// Public root certificates (not secrets). ISRG Root X1 (RSA) + ISRG Root X2 (ECDSA)."
echo "#pragma once"
echo "static const char AG_ROOT_CA_PEM[] ="
cat "$TMP/x1.pem" "$TMP/x2.pem" | tr -d '\r' | sed 's/^/"/; s/$/\\n"/'
echo ";"

# Validate: the server chain must verify against the bundle we just emitted.
cat "$TMP/x1.pem" "$TMP/x2.pem" > "$TMP/bundle.pem"
if echo | openssl s_client -connect "$HOST:443" -servername "$HOST" -CAfile "$TMP/bundle.pem" 2>/dev/null \
     | grep -q "Verify return code: 0"; then
  echo ">> OK: $HOST verifies against the emitted bundle" >&2
else
  echo ">> WARNING: $HOST did NOT verify against X1+X2. Inspect the chain above and add its root." >&2
fi
